-- Niet Café 48: ПЕРЕПРОДАЖА (покупной товар: кола, вода, соки в бутылках, снеки…).
-- Supabase -> SQL Editor -> вставить всё -> Run. Можно запускать повторно.
--
--   • У блюда появляется галочка «🏷 Перепродажа». Для таких позиций программа считает только
--     прибыль = цена продажи − закупка и наценку %. Накладные (аренда, зарплата…) на них не делятся,
--     подсказки «фудкост 30 %» нет — фудкост у покупного товара всегда высокий, и это нормально.
--   • В техкарту такой позиции кладётся сам товар (например, «Кока-Кола 0,5 л» — 1 шт): тогда
--     закупочная цена берётся со склада и при продаже бутылка списывается.

alter table dishes add column if not exists resale boolean not null default false;

notify pgrst, 'reload schema';

select count(*) filter (where resale) as "Позиций перепродажи" from dishes;

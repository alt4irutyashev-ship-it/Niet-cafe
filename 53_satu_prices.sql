select "Результат", "Продукт", "Ед.", "Было, ₸", "Стало, ₸", "Источник" from (
  select case st when 'ok' then 1 when 'same' then 2 else 3 end ord,
         case st when 'ok' then '✅ цена с satu.kz' when 'same' then '✅ уже такая'
                 when 'skip_inv' then '⏭ не тронуто: есть цена из накладной' else '⚠ не тронуто: другая единица у вас' end "Результат",
         name "Продукт", unit "Ед.", trim_scale(old_price) "Было, ₸", trim_scale(new_price) "Стало, ₸", src "Источник"
    from r53
  union all
  select 4, '⬜ цена 0: нет на satu.kz / своё приготовление', p.name, p.unit, 0, null, null
    from products p
   where not coalesce(p.archived,false) and coalesce(p.price,0) = 0
     and exists (select 1 from recipes x join dishes d on d.id = x.dish_id and not coalesce(d.archived,false) where x.product_id = p.id)
) t
order by ord, "Продукт";
